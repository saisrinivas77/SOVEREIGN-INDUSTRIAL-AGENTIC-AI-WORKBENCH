"""
Task endpoints conforming to MASTER/03_API_CONTRACTS.md.
"""

from fastapi import APIRouter
from backend.services.task_service import task_service
from backend.schemas.task import TaskCreate, TaskCreateResponse, TaskRunResponse, TaskStatusResponse

router = APIRouter(prefix="/tasks", tags=["Tasks"])


@router.get("", status_code=200)
async def list_tasks():
    """
    Returns all sovereign tasks.
    """
    from backend.services.database import db
    return {"tasks": db.list_all_tasks()}


@router.post("", response_model=TaskCreateResponse, status_code=200)
async def create_task(payload: TaskCreate) -> TaskCreateResponse:
    """
    Creates a new sovereign task with instruction and optional file IDs.
    """
    return task_service.create_task(
        instruction=payload.instruction,
        file_ids=payload.file_ids,
    )


@router.post("/{task_id}/run", response_model=TaskRunResponse, status_code=200)
async def run_task(task_id: str) -> TaskRunResponse:
    """
    Starts execution of an existing queued task.
    """
    return task_service.run_task(task_id=task_id)


@router.get("/{task_id}", response_model=TaskStatusResponse, status_code=200)
async def get_task_status(task_id: str) -> TaskStatusResponse:
    """
    Retrieves task status, steps, citations, and verified artifacts.
    """
    return task_service.get_task_status(task_id=task_id)


@router.get("/{task_id}/trace", status_code=200)
async def get_task_trace(task_id: str):
    """
    Retrieves agent execution trace for a task.
    """
    status = task_service.get_task_status(task_id=task_id)
    return {
        "task_id": status.task_id,
        "status": status.status,
        "steps": [s.model_dump() for s in status.steps],
    }


@router.get("/{task_id}/artifacts", status_code=200)
async def get_task_artifacts(task_id: str):
    """
    Retrieves artifacts generated by a task.
    """
    status = task_service.get_task_status(task_id=task_id)
    return {
        "task_id": status.task_id,
        "artifacts": [a.model_dump() for a in status.artifacts],
    }

