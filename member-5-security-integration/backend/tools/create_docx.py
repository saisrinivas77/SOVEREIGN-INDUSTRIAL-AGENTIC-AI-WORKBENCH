"""
Create DOCX Tool.
Generates genuine Microsoft Word (.docx) documents with title, styled headings,
and content sections. Verifies document integrity with SHA-256 hash.
"""

import uuid
from pathlib import Path
from typing import Any, Dict, List, Optional
import docx
from docx.shared import Inches, Pt, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH

try:
    from backend.tools.base import BaseTool, ToolResult, Artifact, compute_file_sha256
    from backend.security.security_manager import security_manager
    from backend.security.path_validator import path_validator
    from infra.runtime_config import RuntimeConfig
except ImportError:
    import sys
    from pathlib import Path
    _pkg_root = Path(__file__).resolve().parent.parent.parent
    if str(_pkg_root) not in sys.path:
        sys.path.insert(0, str(_pkg_root))
    from backend.tools.base import BaseTool, ToolResult, Artifact, compute_file_sha256
    from backend.security.security_manager import security_manager
    from backend.security.path_validator import path_validator
    from infra.runtime_config import RuntimeConfig

class CreateDocxTool(BaseTool):
    name = "create_docx"
    description = "Generate a verified Microsoft Word (.docx) report, approval note, or maintenance summary."
    input_schema = {
        "type": "object",
        "properties": {
            "title": {"type": "string", "description": "Document title"},
            "sections": {
                "type": "array",
                "items": {
                    "type": "object",
                    "properties": {
                        "heading": {"type": "string"},
                        "content": {"type": "string"}
                    },
                    "required": ["heading", "content"]
                },
                "description": "List of document sections"
            },
            "filename": {"type": "string", "description": "Optional output filename", "default": "approval_note.docx"}
        },
        "required": ["title", "sections"]
    }
    permission = "artifact:create"
    timeout_seconds = 30

    def execute(self, arguments: Dict[str, Any], context: Optional[Dict[str, Any]] = None) -> ToolResult:
        title = arguments.get("title", "Sovereign Industrial Report")
        sections = arguments.get("sections", [])
        raw_filename = arguments.get("filename", "approval_note.docx")
        if not raw_filename.endswith(".docx"):
            raw_filename += ".docx"

        safe_filename = path_validator.sanitize_filename(raw_filename)
        task_id = context.get("task_id") if context else None
        artifact_id = f"ART-{uuid.uuid4().hex[:6].upper()}"

        try:
            # Create outputs directory for artifact
            art_dir = (RuntimeConfig.OUTPUTS_DIR / artifact_id).resolve()
            art_dir.mkdir(parents=True, exist_ok=True)
            doc_path = (art_dir / safe_filename).resolve()

            # Build Document
            doc = docx.Document()

            # Set standard margins
            for sec in doc.sections:
                sec.top_margin = Inches(1)
                sec.bottom_margin = Inches(1)
                sec.left_margin = Inches(1)
                sec.right_margin = Inches(1)

            # Title
            title_p = doc.add_paragraph()
            title_run = title_p.add_run(title)
            title_run.font.size = Pt(20)
            title_run.font.bold = True
            title_run.font.color.rgb = RGBColor(20, 35, 60)
            title_p.paragraph_format.space_after = Pt(12)

            # Subtitle / Metadata banner
            sub_p = doc.add_paragraph()
            sub_run = sub_p.add_run("CONFIDENTIAL & PROPRIETARY — GENERATED BY SOVEREIGN AI WORKBENCH")
            sub_run.font.size = Pt(8.5)
            sub_run.font.italic = True
            sub_run.font.color.rgb = RGBColor(120, 120, 120)
            sub_p.paragraph_format.space_after = Pt(18)

            # Add Sections
            for s in sections:
                heading = s.get("heading", "Section")
                content = s.get("content", "")

                h_p = doc.add_paragraph()
                h_run = h_p.add_run(heading)
                h_run.font.size = Pt(13)
                h_run.font.bold = True
                h_run.font.color.rgb = RGBColor(30, 60, 100)
                h_p.paragraph_format.space_before = Pt(12)
                h_p.paragraph_format.space_after = Pt(4)

                c_p = doc.add_paragraph()
                c_run = c_p.add_run(content)
                c_run.font.size = Pt(10.5)
                c_p.paragraph_format.space_after = Pt(8)

            # Save file
            doc.save(str(doc_path))

            # Verify file existence and readability
            if not doc_path.exists() or doc_path.stat().st_size == 0:
                raise IOError(f"Failed to generate valid DOCX at {doc_path}")

            # Verify readability with docx
            _ = docx.Document(str(doc_path))

            # Compute SHA-256
            sha256_hash = compute_file_sha256(doc_path)

            rel_path = str(doc_path.relative_to(RuntimeConfig.BASE_DIR))

            # Record in Security & Audit
            security_manager.record_artifact_creation(
                artifact_id=artifact_id,
                filename=safe_filename,
                path_str=rel_path,
                sha256=sha256_hash,
                verified=True,
                task_id=task_id
            )

            # Register as file in workspace for any downstream tools
            with open(doc_path, "rb") as f:
                path_validator.register_file(artifact_id, safe_filename, f.read())

            artifact = Artifact(
                artifact_id=artifact_id,
                filename=safe_filename,
                type="docx",
                path=rel_path,
                sha256=sha256_hash,
                verified=True
            )

            return ToolResult(
                success=True,
                status="completed",
                result=artifact.model_dump()
            )

        except Exception as e:
            return ToolResult(
                success=False,
                status="failed",
                error=f"DOCX generation failed: {str(e)}"
            )
